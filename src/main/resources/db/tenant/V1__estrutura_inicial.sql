-- Estrutura de UMA empresa. Executada pela aplicação dentro do schema empresa_<id>,
-- já com SET ROLE empresa_<id> e search_path apontando para esse schema.
-- Não escreva nome de schema aqui: tudo cai no schema da empresa atual.
-- Colunas e tipos espelham as entidades JPA (Cliente, Produto, Comanda, ItemComanda).

CREATE TABLE cliente (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome     varchar(120) NOT NULL,
    telefone varchar(20),
    endereco varchar(255)
);

CREATE TABLE produto (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       varchar(255),
    descricao  varchar(255),
    categoria  varchar(255),
    quantidade integer          NOT NULL,
    preco      double precision NOT NULL,
    foto       bytea,
    foto_tipo  varchar(255)
);

CREATE TABLE comanda (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano_mes      varchar(7)    NOT NULL,
    numero_mes   integer       NOT NULL,
    data_hora    timestamp(6)  NOT NULL,
    mesa         varchar(20),
    cliente_id   bigint REFERENCES cliente (id),
    cliente_nome varchar(120)  NOT NULL,
    telefone     varchar(20),
    endereco     varchar(255),
    observacoes  varchar(500),
    total        numeric(12,2) NOT NULL,
    CONSTRAINT uk_comanda_ano_mes_numero UNIQUE (ano_mes, numero_mes)
);

CREATE TABLE item_comanda (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comanda_id     bigint        NOT NULL REFERENCES comanda (id),
    produto_id     bigint        REFERENCES produto (id),
    nome_produto   varchar(255)  NOT NULL,
    preco_unitario numeric(12,2) NOT NULL,
    quantidade     integer       NOT NULL
);

CREATE INDEX ix_comanda_data_hora   ON comanda (data_hora);
CREATE INDEX ix_comanda_cliente     ON comanda (cliente_id);
CREATE INDEX ix_item_comanda_comanda ON item_comanda (comanda_id);
CREATE INDEX ix_item_comanda_produto ON item_comanda (produto_id);
